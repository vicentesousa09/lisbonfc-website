const mediaSlugs = Object.keys(mediaData);
const requestedVideo = new URLSearchParams(window.location.search).get("video");
const activeVideoSlug = mediaData[requestedVideo] ? requestedVideo : mediaSlugs[0];
const activeMedia = mediaData[activeVideoSlug];

function renderVideo() {
  document.title = `${activeMedia.title} | Lisbon FC`;

  document.querySelectorAll("[data-video-tag]").forEach((el) => { el.textContent = activeMedia.tagLabel; });
  document.querySelectorAll("[data-video-title]").forEach((el) => { el.textContent = activeMedia.title; });
  document.querySelectorAll("[data-video-date]").forEach((el) => { el.textContent = activeMedia.dateLabel; });

  const leadEl = document.getElementById("videoLead");
  if (leadEl) leadEl.textContent = activeMedia.lead;

  const mediaEl = document.getElementById("videoMedia");
  if (mediaEl) {
    mediaEl.innerHTML = "";
    const media = activeMedia.media;
    mediaEl.classList.toggle("noticia-media--gallery", media.type === "gallery");

    if (media.type === "gallery") {
      const grid = document.createElement("div");
      grid.className = "noticia-gallery";
      media.gallery.forEach((src) => {
        const item = document.createElement("div");
        item.className = "noticia-gallery-item";
        const img = document.createElement("div");
        img.className = "noticia-gallery-img";
        img.style.backgroundImage = `url('${src}')`;
        item.appendChild(img);
        item.addEventListener("click", () => openLightbox(media.gallery, media.gallery.indexOf(src), media.galleryCaptions));
        grid.appendChild(item);
      });
      mediaEl.appendChild(grid);
    } else {
      mediaEl.appendChild(buildVideoPlayer(media));
    }
  }

  const relatedEl = document.getElementById("videoRelacionados");
  if (relatedEl) {
    relatedEl.innerHTML = "";
    mediaSlugs
      .filter((slug) => slug !== activeVideoSlug)
      .filter((slug) => mediaData[slug].tagLabel === activeMedia.tagLabel)
      .slice(0, 3)
      .forEach((slug) => {
        const related = mediaData[slug];
        const card = document.createElement("a");
        card.className = "news-card";
        card.href = `video?video=${slug}`;

        const media = related.media;
        const bgImage = media.type === "gallery" ? media.gallery[0] : media.crest;
        const bgStyle = `background-image:url('${bgImage}');background-size:cover;background-position:center;`;

        card.innerHTML = `
          <div class="news-image"><div class="news-media" style="${bgStyle}"></div></div>
          <span class="news-tag">${related.tagLabel}</span>
          <h3>${related.title}</h3>
          <p>${related.lead}</p>
          <span class="news-date">${related.dateLabel}</span>
        `;
        relatedEl.appendChild(card);
      });
  }
}

renderVideo();
